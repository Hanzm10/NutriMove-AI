// Builds supabase/seed/foods_fnri.sql (idempotent upsert) from supabase/seed/foods_fnri.csv.
// Usage: node scripts/build-food-seed.mjs  → then run the SQL in the Supabase SQL editor or `psql`.
import { readFileSync, writeFileSync } from "node:fs";

const csv = readFileSync(new URL("../supabase/seed/foods_fnri.csv", import.meta.url), "utf8").trim();
const [header, ...lines] = parseCsv(csv);
const rows = lines.map((cells) => Object.fromEntries(header.map((h, i) => [h, cells[i] ?? ""])));

const q = (s) => (s === "" ? "null" : `'${s.replaceAll("'", "''")}'`);
const n = (s) => (s === "" ? "0" : String(Number(s)));
const values = rows.map(
  (r) =>
    `('fnri', ${q(r.external_id)}, ${q(r.name)}, ${q(r.name_local)}, 100, '100 g', ${n(r.kcal_100g)}, ${n(r.protein_100g)}, ${n(r.carbs_100g)}, ${n(r.fat_100g)}, ${n(r.fiber_100g)}, ${q(r.source_ref)})`,
);
const sql = `-- Generated by scripts/build-food-seed.mjs from foods_fnri.csv (${rows.length} rows). Do not edit by hand.
-- Source: DOST-FNRI Philippine Food Composition Tables (PhilFCT), values per 100 g edible portion.
insert into public.foods (source, external_id, name, name_local, serving_g, serving_label,
  kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g, source_ref)
values
${values.join(",\n")}
on conflict (source, external_id) do update set
  name = excluded.name, name_local = excluded.name_local, kcal_100g = excluded.kcal_100g,
  protein_100g = excluded.protein_100g, carbs_100g = excluded.carbs_100g, fat_100g = excluded.fat_100g,
  fiber_100g = excluded.fiber_100g, source_ref = excluded.source_ref;
`;
writeFileSync(new URL("../supabase/seed/foods_fnri.sql", import.meta.url), sql);
console.log(`wrote ${rows.length} rows`);

function parseCsv(text) {
  const out = [];
  let row = [], cell = "", inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') inQ = false;
      else cell += c;
    } else if (c === '"') inQ = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n") { row.push(cell.replace(/\r$/, "")); out.push(row); row = []; cell = ""; }
    else cell += c;
  }
  row.push(cell);
  out.push(row);
  return out;
}
