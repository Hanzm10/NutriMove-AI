// Builds supabase/seed/recipes.json + recipes.sql (idempotent upsert) from recipes.source.json.
// Per-serving nutrition is summed from DOST-FNRI PhilFCT rows (foods_fnri.csv, per 100 g edible portion);
// allergens and diet pattern are derived from the ingredient IDs so they can't drift from the ingredients.
// Usage: node scripts/build-recipe-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const seed = (p) => new URL(`../supabase/seed/${p}`, import.meta.url);
const foods = new Map(
  JSON.parse(readFileSync(seed("foods_fnri.json"), "utf8")).map((f) => [f.external_id, f]),
);
const { recipes } = JSON.parse(readFileSync(seed("recipes.source.json"), "utf8"));

// Ingredient ID → allergen / animal-product category.
const ALLERGEN_IDS = {
  fish: ["G074", "G105", "G145", "G203", "G207", "G226", "N011"],
  shellfish: ["G085", "G113", "G131", "N020"],
  egg: ["H003", "H004"],
  milk: ["J014", "J015", "J026"],
  soy: ["C063", "C064", "N023"],
  wheat: ["A031", "A042", "A140", "A152", "A153", "N023"],
  peanut: ["C038", "C058"],
};
const isMeat = (id) => id.startsWith("F");
const isSeafood = (id) => [...ALLERGEN_IDS.fish, ...ALLERGEN_IDS.shellfish].includes(id);
const PROTEIN_TAGS = [
  ["chicken", (id) => ["F093", "F107"].includes(id)],
  ["pork", (id) => ["F173", "F174"].includes(id)],
  ["beef", (id) => ["F035", "F038"].includes(id)],
  ["seafood", (id) => isSeafood(id) && !["N011", "N020"].includes(id)],
];
const SLOTS = ["breakfast", "lunch", "dinner", "snack"];
const TAGS = ["soup", "rice_dish", "vegetable", "seafood", "chicken", "pork", "beef", "egg", "noodle"];

const round = (x, d = 1) => Math.round(x * 10 ** d) / 10 ** d;
const out = recipes.map((r) => {
  const total = { kcal: 0, protein: 0, carbs: 0, fat: 0, fiber: 0, grams: 0 };
  const ids = new Set();
  const ingredients = r.ingredients.map(([id, grams, label]) => {
    total.grams += grams;
    if (id) {
      const f = foods.get(id);
      if (!f) throw new Error(`${r.slug}: unknown FNRI id ${id}`);
      ids.add(id);
      const k = grams / 100;
      total.kcal += f.kcal_100g * k;
      total.protein += f.protein_100g * k;
      total.carbs += f.carbs_100g * k;
      total.fat += f.fat_100g * k;
      total.fiber += (f.fiber_100g ?? 0) * k;
    }
    return { name: label, grams, fnri_id: id };
  });
  for (const s of r.slots) if (!SLOTS.includes(s)) throw new Error(`${r.slug}: bad slot ${s}`);
  const tags = new Set(r.tags);
  for (const [tag, test] of PROTEIN_TAGS) if ([...ids].some(test)) tags.add(tag);
  // "egg" only when egg is a main component, not a garnish.
  if (r.ingredients.some(([id, g]) => ["H003", "H004"].includes(id) && g >= 100)) tags.add("egg");
  for (const t of tags) if (!TAGS.includes(t)) throw new Error(`${r.slug}: bad tag ${t}`);
  const allergens = Object.entries(ALLERGEN_IDS)
    .filter(([, list]) => list.some((id) => ids.has(id)))
    .map(([a]) => a);
  const diet = [...ids].some(isMeat) ? "omnivore" : [...ids].some(isSeafood) ? "pescatarian" : "vegetarian";
  return {
    slug: r.slug,
    name: r.name,
    is_filipino: r.filipino,
    meal_slots: r.slots,
    tags: TAGS.filter((t) => tags.has(t)),
    allergens,
    diet_pattern: diet,
    cost_level: r.cost,
    prep_minutes: r.prep,
    serving_g: round(total.grams, 0),
    kcal: round(total.kcal, 0),
    protein_g: round(total.protein),
    carbs_g: round(total.carbs),
    fat_g: round(total.fat),
    fiber_g: round(total.fiber),
    ingredients,
    instructions: r.steps,
    source_ref: `Nutrition computed per serving from DOST-FNRI PhilFCT food IDs ${[...ids].sort().join(", ")}`,
  };
});

const slugs = new Set(out.map((r) => r.slug));
if (slugs.size !== out.length) throw new Error("duplicate slug");

writeFileSync(seed("recipes.json"), JSON.stringify(out, null, 2) + "\n");

const q = (s) => (s == null ? "null" : `'${String(s).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const values = out.map(
  (r) =>
    `(${q(r.slug)}, ${q(r.name)}, ${r.is_filipino}, ${arr(r.meal_slots)}, ${arr(r.tags)}, ${arr(r.allergens)}, ${q(r.diet_pattern)}, ${q(r.cost_level)}, ${r.prep_minutes}, ${r.serving_g}, ${r.kcal}, ${r.protein_g}, ${r.carbs_g}, ${r.fat_g}, ${r.fiber_g}, ${q(JSON.stringify(r.ingredients))}::jsonb, ${q(r.instructions)}, ${q(r.source_ref)})`,
);
const sql = `-- Generated by scripts/build-recipe-seed.mjs from recipes.source.json (${out.length} recipes). Do not edit by hand.
insert into public.recipes (slug, name, is_filipino, meal_slots, tags, allergens, diet_pattern, cost_level,
  prep_minutes, serving_g, kcal, protein_g, carbs_g, fat_g, fiber_g, ingredients, instructions, source_ref)
values
${values.join(",\n")}
on conflict (slug) do update set
  name = excluded.name, is_filipino = excluded.is_filipino, meal_slots = excluded.meal_slots, tags = excluded.tags,
  allergens = excluded.allergens, diet_pattern = excluded.diet_pattern, cost_level = excluded.cost_level,
  prep_minutes = excluded.prep_minutes, serving_g = excluded.serving_g, kcal = excluded.kcal,
  protein_g = excluded.protein_g, carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fiber_g = excluded.fiber_g,
  ingredients = excluded.ingredients, instructions = excluded.instructions, source_ref = excluded.source_ref;
`;
writeFileSync(seed("recipes.sql"), sql);
const fil = out.filter((r) => r.is_filipino).length;
console.log(`wrote ${out.length} recipes (${fil} Filipino, ${Math.round((fil / out.length) * 100)}%)`);
